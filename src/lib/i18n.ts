export function translate(locale: Locale, key: TKey, vars?: Record<string, string | number>) {
  let s: string = dictionaries[locale][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

